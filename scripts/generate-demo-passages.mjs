// Generated server allowlist: only this public demonstration text can spend
// anonymous generation budget. Never send arbitrary visitor prompts to AI.
import { readdir, readFile, mkdir, writeFile } from "node:fs/promises";
const locales = new URL("../artifacts/reading-companion/public/locales/", import.meta.url);
const passages = {};
for (const locale of (await readdir(locales)).sort()) {
  const content = JSON.parse(await readFile(new URL(`${locale}/translation.json`, locales), "utf8"));
  passages[locale] = content.demo.guided.passage;
}
const output = new URL("../artifacts/api-server/src/generated/", import.meta.url);
await mkdir(output, { recursive: true });
await writeFile(new URL("demo-passages.ts", output),
  "// Generated by scripts/generate-demo-passages.mjs. Do not edit.\nexport default " +
  JSON.stringify(passages, null, 2) + " as const;\n");
